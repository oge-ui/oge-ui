// Writes src/license.ts from the OGE_LICENSE_KEY environment variable, so the
// key never lands in the repository. Runs before start/dev/build; without the
// variable the key is empty, which is fine on localhost (OGE UI Pro stays
// silent in development) and shows the "unlicensed" notice in production.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const key = (process.env.OGE_LICENSE_KEY ?? '').trim();
const target = fileURLToPath(new URL('../src/license.ts', import.meta.url));
writeFileSync(
  target,
  `// Generated by scripts/write-license.mjs from OGE_LICENSE_KEY — do not commit.\nexport const OGE_LICENSE_KEY = ${JSON.stringify(key)};\n`,
);
console.log(key ? 'OGE UI Pro license key written.' : 'No OGE_LICENSE_KEY set; running unlicensed.');
