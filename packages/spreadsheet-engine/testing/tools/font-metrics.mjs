// Turns testing/captures/font-metrics.json (measured in Excel by capture.ps1)
// into src/lib/metrics/font-metrics-data.ts: per font, the maximum digit width
// and the single-line row height for every pixel em size, delta-encoded.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const capture = JSON.parse(
  readFileSync(join(root, 'testing', 'captures', 'font-metrics.json'), 'utf8'),
);
const environment = JSON.parse(
  readFileSync(join(root, 'testing', 'captures', 'environment.json'), 'utf8'),
);

const MAX_PPEM = 96;
const encode = (values) => {
  let previous = 0;
  let out = '';
  for (const value of values) {
    const delta = value - previous;
    if (delta < -31 || delta > 20)
      throw new Error(`delta ${delta} out of range`);
    // 'a'..'z' = −5..+20 ('f' is 0); 'A'..'Z' = −6..−31, for bitmap fonts' jumps
    out += String.fromCharCode(delta >= -5 ? 102 + delta : 59 - delta);
    previous = value;
  }
  return out;
};

const rows = [];
for (const { font, resolved, sizes } of capture.fonts) {
  const mdw = new Array(MAX_PPEM).fill(undefined);
  const line = new Array(MAX_PPEM).fill(undefined);
  for (const entry of sizes) {
    const [pt, w10, w20, , rowPx] = String(entry)
      .split('|')
      .map((s) => Number(s.replace(',', '.')));
    const ppem = Math.round((pt * 4) / 3);
    if (ppem < 1 || ppem > MAX_PPEM) continue;
    const digit = Math.round((w20 - w10) / 10);
    const pad = Math.round(w10 - 10 * digit);
    if (pad !== 2 * Math.ceil(digit / 4) + 1)
      throw new Error(`${font} ${pt}: padding ${pad} breaks the rule`);
    if (mdw[ppem - 1] !== undefined && mdw[ppem - 1] !== digit)
      throw new Error(`${font} ppem ${ppem}: two widths`);
    mdw[ppem - 1] = digit;
    line[ppem - 1] = Math.round(rowPx);
  }
  if (mdw.includes(undefined))
    throw new Error(`${font}: a pixel size is missing`);
  rows.push(
    `  ${JSON.stringify(font.toLowerCase())}: [${JSON.stringify(encode(mdw))}, ${JSON.stringify(encode(line))}],${resolved !== font ? ` // Excel uses ${resolved}` : ''}`,
  );
}

const out = `// Generated by testing/tools/font-metrics.mjs from testing/captures/font-metrics.json — do not edit.
//
// Measured in Excel ${environment.excelVersion} (build ${environment.excelBuild}) at ${environment.dpi} dpi: for each
// font and pixel em size 1–${MAX_PPEM} (round(points × 4 / 3)), the maximum digit width and the
// height of a one-line row, in pixels. Each string is a run of deltas from the previous
// size, one character each ('f' = +0, 'g' = +1, 'e' = −1 …, 'A' = −6, 'B' = −7 …).
export const OGE_FONT_METRICS_DATA: Readonly<Record<string, readonly [string, string]>> = {
${rows.join('\n')}
};
`;
writeFileSync(join(root, 'src', 'lib', 'metrics', 'font-metrics-data.ts'), out);
console.log(`font metrics: ${rows.length} fonts`);
