/**
 * Every (format, value) pair the corpus asks Excel to display: the rows of
 * `number-format.spec.ts` (Microsoft examples, Excel-derived and inferred
 * behaviour) plus built-in ids and cases the paint model relies on. The
 * capture stores Excel's text for each; `number-format.corpus.spec.ts`
 * compares the renderer with it.
 */
import { ogeDatePartsToSerial } from '../../src/lib/date/date-serial';

/** A format (code, or built-in id) and a value (numbers, text or a boolean). */
export type NumberFormatCase = readonly [
  format: string | number,
  value: number | string | boolean,
];

const serial = (y: number, m: number, d: number, h = 0, min = 0, s = 0) =>
  ogeDatePartsToSerial({
    year: y,
    month: m,
    day: d,
    hour: h,
    minute: min,
    second: s,
  }) ?? Number.NaN;
const time = (h: number, m: number, s: number) =>
  (h * 3600 + m * 60 + s) / 86400;

