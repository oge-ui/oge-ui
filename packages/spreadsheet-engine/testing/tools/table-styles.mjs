// Turns testing/captures/table-styles.json (Excel's built-in table styles,
// read through COM by table-styles.ps1) into src/lib/model/table-styles-data.ts:
// one short string per style, decoded by `model/table-styles.ts`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const capture = JSON.parse(
  readFileSync(join(root, 'testing', 'captures', 'table-styles.json'), 'utf8'),
);

const ELEMENTS = {
  wholeTable: 'w',
  headerRow: 'h',
  totalRow: 't',
  firstColumn: 'f',
  lastColumn: 'l',
  firstRowStripe: 'r1',
  secondRowStripe: 'r2',
  firstColumnStripe: 'c1',
  secondColumnStripe: 'c2',
  firstHeaderCell: 'fh',
  lastHeaderCell: 'lh',
  firstTotalCell: 'ft',
  lastTotalCell: 'lt',
};
const EDGES = {
  left: 'L',
  right: 'R',
  top: 'T',
  bottom: 'B',
  vertical: 'V',
  horizontal: 'H',
};
// XlLineStyle/XlBorderWeight → SpreadsheetML border style → one letter: the
// styles Excel's built-in table styles use (the decoder reads no others)
const STYLES = {
  '1/2': 't', // thin
  '1/-4138': 'm', // medium
  '1/4': 'k', // thick
  '-4119/4': 'd', // double
};

// Excel stores a tint as a 16-bit fraction of 32767, cut from two decimals
const tintOf = (hundredths) => Math.trunc((hundredths * 32767) / 100) / 32767;

const colour = (color, where) => {
  if (!color || color.theme === undefined)
    throw new Error(`${where}: not a theme colour`);
  if (!color.tint) return String(color.theme);
  const hundredths = Math.round(color.tint * 100);
  if (tintOf(hundredths) !== color.tint)
    throw new Error(`${where}: tint ${color.tint} is not a two-decimal one`);
  return `${color.theme}${hundredths > 0 ? '+' : ''}${hundredths}`;
};

const lines = [];
for (const style of capture.styles) {
  const elements = [];
  for (const [type, element] of Object.entries(style.elements)) {
    const key = ELEMENTS[type];
    if (!key) throw new Error(`${style.name}: unknown element ${type}`);
    const where = `${style.name} ${type}`;
    const tokens = [];
    if (element.fill) {
      if (element.fill.pattern !== 1)
        throw new Error(`${where}: pattern ${element.fill.pattern}`);
      tokens.push(`F${colour(element.fill.color, where)}`);
    }
    const font = element.font ?? {};
    if (
      font.italic ||
      font.strikethrough ||
      (font.underline ?? -4142) !== -4142
    )
      throw new Error(`${where}: a font flag the decoder does not read`);
    if (font.bold) tokens.push('b');
    if (font.color) tokens.push(`c${colour(font.color, where)}`);
    for (const [edge, border] of Object.entries(element.borders ?? {})) {
      const letter = STYLES[`${border.lineStyle}/${border.weight}`];
      if (!letter)
        throw new Error(
          `${where}: border ${border.lineStyle}/${border.weight}`,
        );
      tokens.push(`${EDGES[edge]}${letter}${colour(border.color, where)}`);
    }
    if (element.size)
      throw new Error(`${where}: a stripe size the decoder does not read`);
    elements.push(`${key}:${tokens.join(',')}`);
  }
  lines.push(
    `  ${JSON.stringify(style.name)}: ${JSON.stringify(elements.join(';'))},`,
  );
}

const out = join(root, 'src', 'lib', 'model', 'table-styles-data.ts');
writeFileSync(
  out,
  `// Generated by testing/tools/table-styles.mjs from testing/captures/table-styles.json — do not edit.
//
// Excel's ${capture.styles.length} built-in table styles, read through COM from Excel ${capture.excelVersion} (build ${capture.excelBuild}).
// A style is its elements separated by ';' — w whole table, h header row, t total row, f first
// column, l last column, r1/r2 row stripes, c1/c2 column stripes — each a list of ',' tokens:
// F + colour a solid fill, c + colour the font colour, b bold, and a border: its edge (L R T B,
// V/H inside), its style (t thin, m medium, k thick, d double) and colour. A colour is a theme
// index with an optional tint in hundredths (4+40).
export const OGE_TABLE_STYLES_DATA: Readonly<Record<string, string>> = {
${lines.join('\n')}
};
`,
);
console.log(`table styles: ${capture.styles.length} → ${out}`);
