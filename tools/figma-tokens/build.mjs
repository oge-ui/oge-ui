#!/usr/bin/env node
/**
 * Builds the OGE UI Figma plugin (P-8): bundles `src/plugin.ts` with the
 * shipped variable collection (from `packages/core/tokens.json`) inlined,
 * writes the plugin to `dist/figma-plugin/` and a deterministic zip of it to
 * `apps/dev-app/public/figma/oge-ui-figma-plugin.zip`, which the tokens page
 * links. `--check` fails when the committed zip is out of date.
 */
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../..',
);
const here = path.join(root, 'tools/figma-tokens');
const check = process.argv.includes('--check');
const zipOut = path.join(
  root,
  'apps/dev-app/public/figma/oge-ui-figma-plugin.zip',
);

// the converter, loaded once to compute the shipped collection
const scratch = mkdtempSync(path.join(tmpdir(), 'oge-figma-'));
const convertJs = path.join(scratch, 'convert.mjs');
await esbuild.build({
  entryPoints: [path.join(here, 'src/convert.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: convertJs,
  logLevel: 'error',
});
const { ogeTokensToFigma } = await import(pathToFileURL(convertJs).href);
rmSync(scratch, { recursive: true, force: true });
const tokens = JSON.parse(
  readFileSync(path.join(root, 'packages/core/tokens.json'), 'utf8'),
);
const collection = ogeTokensToFigma(tokens);

const bundle = await esbuild.build({
  entryPoints: [path.join(here, 'src/plugin.ts')],
  bundle: true,
  format: 'iife',
  // Figma's plugin sandbox runs ES2017-level JavaScript
  target: 'es2017',
  write: false,
  minify: false,
  legalComments: 'none',
  define: { __OGE_COLLECTION__: JSON.stringify(collection) },
  logLevel: 'error',
});
const code = `// OGE UI — Figma tokens plugin (generated by tools/figma-tokens/build.mjs)
${bundle.outputFiles[0].text}`;
const ui = readFileSync(path.join(here, 'src/ui.html'), 'utf8');
const manifest = `${JSON.stringify(
  {
    name: 'OGE UI tokens',
    id: 'oge-ui-tokens',
    api: '1.0.0',
    main: 'code.js',
    ui: 'ui.html',
    editorType: ['figma', 'dev'],
    documentAccess: 'dynamic-page',
    networkAccess: { allowedDomains: ['none'] },
  },
  null,
  2,
)}\n`;
const files = [
  ['manifest.json', manifest],
  ['code.js', code],
  ['ui.html', ui],
];

// --- a deterministic zip (stored, fixed timestamps) ---------------------------
const CRC = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc32 = (bytes) => {
  let c = 0xffffffff;
  for (const b of bytes) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
function zip(entries) {
  const locals = [];
  const centrals = [];
  let offset = 0;
  // 1980-01-01 00:00 — DOS time zero, so the bytes never change by themselves
  const DOS_TIME = 0;
  const DOS_DATE = (0 << 9) | (1 << 5) | 1;
  for (const [name, text] of entries) {
    const data = Buffer.from(text, 'utf8');
    const nameBytes = Buffer.from(`oge-ui-figma-plugin/${name}`, 'utf8');
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6); // UTF-8 names
    local.writeUInt16LE(0, 8); // stored
    local.writeUInt16LE(DOS_TIME, 10);
    local.writeUInt16LE(DOS_DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBytes.length, 26);
    locals.push(local, nameBytes, data);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(0, 10);
    central.writeUInt16LE(DOS_TIME, 12);
    central.writeUInt16LE(DOS_DATE, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(data.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBytes.length, 28);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, nameBytes);
    offset += 30 + nameBytes.length + data.length;
  }
  const centralSize = centrals.reduce((n, b) => n + b.length, 0);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(centralSize, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, ...centrals, end]);
}

const archive = zip(files);
if (check) {
  let current = Buffer.alloc(0);
  try {
    current = readFileSync(zipOut);
  } catch {
    // missing
  }
  if (!current.equals(archive)) {
    console.error(
      'figma-tokens: apps/dev-app/public/figma/oge-ui-figma-plugin.zip is out of date — run `node tools/figma-tokens/build.mjs` and commit it.',
    );
    process.exit(1);
  }
  console.log(
    `figma-tokens: plugin zip up to date (${collection.variables.length} variables)`,
  );
} else {
  const dist = path.join(root, 'dist/figma-plugin');
  mkdirSync(dist, { recursive: true });
  for (const [name, text] of files) writeFileSync(path.join(dist, name), text);
  mkdirSync(path.dirname(zipOut), { recursive: true });
  writeFileSync(zipOut, archive);
  console.log(
    `figma-tokens: ${collection.variables.length} variables → dist/figma-plugin and ${path.relative(root, zipOut)}`,
  );
}
